/* 해외 대형 영입 — 이건 평범한 영입 소식이 아니라 리그 전체가 흔들리는 사건이다.
   FC 서울 × 호날두처럼 사연이 있는 경우엔 전용 반응이 한 겹 더 붙는다. */
function socialOnOverseas(p, N){
  const t=userTeam(); if(!p||!t) return;
  const v={p:p.name, f:(N&&N.agreedFee)||p.osFee||0, t:t.short, c:p.osClub||""};
  /* 리그를 뒤흔드는 영입과, 그냥 한 명 더 데려온 영입은 반응의 크기부터 다르다 */
  const tier=p.osTier||"big";
  const big = tier==="big";
  if(tier==="big"){
    socialFill(SOC.osBig, 3+R(3), 1, v);
    fmkFill(FMK.osBig, 3+R(3), v);
    rivalFill(RIV.osBig, 3+R(2), 0, v);
    rivalFmk(FRIV.osBig, 2+R(2), v);
  } else if(tier==="minor"){
    socialFill(SOC.osMinor, 2+R(2), 0, v);
    fmkFill(FMK.osMinor, 2+R(3), v);
    rivalFill(RIV.osMinor, 1+R(2), 0, v);
    rivalFmk(FRIV.osMinor, 1+R(2), v);
  }
  /* tier "mid" — 리그를 뒤흔들 영입도, 시큰둥한 영입도 아니다.
     socialOnSigning() 이 이미 채워 준 평범한 영입 반응으로 충분하다. */
  /* 선수 자체가 화제인 경우 — 어느 구단이 데려가든 붙는 반응 */
  if(p.osPool){
    const q=p.osPool;
    if(SOC[q])  socialFill(SOC[q], 4+R(3), 1, v);
    if(FMK[q])  fmkFill(FMK[q], 4+R(3), v);
    if(RIV[q])  rivalFill(RIV[q], 3+R(3), 0, v);
    if(FRIV[q]) rivalFmk(FRIV[q], 2+R(3), v);
  }
  const k = N && N.eggPool;
  if(k){
    if(SOC[k])  socialFill(SOC[k], 5+R(3), 1, v);
    if(FMK[k])  fmkFill(FMK[k], 5+R(3), v);
    if(RIV[k])  rivalFill(RIV[k], 4+R(3), 0, v);
    if(FRIV[k]) rivalFmk(FRIV[k], 3+R(3), v);
    if(big){
      addNews(`📱 SNS가 뜨겁습니다. "${p.name} ${t.short}행" 관련 게시물이 하루 종일 타임라인을 덮었습니다.`);
      addMood(`🔥 라커룸이 술렁입니다. 선수들이 ${p.name}과(와) 같이 뛴다는 사실을 아직 실감하지 못하는 눈치입니다.`);
    }
  }
  saveGame();
}
function socialOnSigning(p, fee){
  if(!p) return;
  const v={p:p.name, f:fee||0};
  /* ⚠ 제보 — 자유계약(이적료 0)인데 「0억을 저기에 쓴다고? ㅅㅂ」이 떴다.
     액수를 놀리는 문구는 돈이 실제로 나갔을 때만 성립한다. 공짜 영입은 결이 다르다. */
  const free = !(fee>0);
  if(free) v.f="자유계약";
  if(fee>=25) socialFill(SOC.signBig, 2, 1, v);
  socialFill(free?SOC.signFree:SOC.sign, 2+R(2), free?1:(fee>=25?1:0), v);
  if((G.season-p.by)<=21) socialFill(SOC.signYouth, 1, 0, v);
  // 커뮤니티는 같은 영입도 훨씬 세게 받는다. 팀 평균보다 나은 선수면 환호, 아니면 조롱.
  const good = p.ovr >= teamOVR(userTeam())+1 || fee>=25;
  fmkFill(free ? (good?FMK.signFreeGood:FMK.signFree)
               : (good?FMK.signGood:FMK.signBad), 2+R(2), v);
  // 남의 집 영입은 남의 집 팬들이 더 시끄럽다 — 놓친 아쉬움, 오버페이 지적, 부러움
  const rv=Object.assign({t:userTeam().short}, v);
  if(fee>=25) rivalFill(RIV.signBig, 2+R(2), 1, rv);
  rivalFill(RIV.sign, 1+R(2), good?1:0, rv);
  if((G.season-p.by)<=21) rivalFill(RIV.signYouth, 1, 0, rv);
  if(G.phase==="pre") rivalFill(RIV.preSign, 1+R(2), 1, rv);   // 겨울 이적시장은 옆 동네가 더 예민하다
  rivalFmk(FRIV.sign, 1+R(2), rv);
  saveGame();
}
