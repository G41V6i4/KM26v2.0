/* 풀에서 서로 다른 항목 n개를 뽑는다.
   예전에는 무작위로 뽑고 겹치면 열 번까지 다시 뽑는 방식이라, 요청 개수가 풀 크기보다 크면
   같은 문장이 연달아 세 번씩 올라왔다(3줄짜리 풀에 5줄을 요청하는 식). 인덱스를 섞어
   앞에서부터 잘라 쓰면 중복이 원천적으로 불가능하고, 풀보다 많이 요청해도 있는 만큼만 나간다. */
function sampleN(list, n){
  if(!list || !list.length) return [];
  const idx=list.map((_,i)=>i);
  for(let i=idx.length-1;i>0;i--){ const j=R(i+1); const tmp=idx[i]; idx[i]=idx[j]; idx[j]=tmp; }
  return idx.slice(0, Math.max(0, Math.min(n, list.length))).map(i=>list[i]);
}
